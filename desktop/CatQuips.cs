        readonly Random random;
        readonly int[] order = new int[Lines.Length];
        int cursor = Lines.Length;
        int previous = -1;
        internal int Count { get { return order.Length; } }
        internal CatQuips(Random random) { this.random = random; }

        internal string Next()
        {
            if (cursor == order.Length)
            {
                for (int i=0; i<order.Length; i++) order[i]=i;
                for (int i=order.Length-1; i>0; i--) Swap(i,random.Next(i+1));
                if (order[0]==previous) Swap(0,1+random.Next(order.Length-1));
                cursor=0;
            }
            previous=order[cursor++];
            return Lines[previous];
        }

        void Swap(int a,int b)
        {
            int tmp=order[a]; order[a]=order[b]; order[b]=tmp;
        }
